    function normalizeLanguage(language) {
        const normalized = String(language || "")
            .toLowerCase()
            .split("-")[0]
        if (normalized === "es") return "en"
        return SUPPORTED_LANGUAGES.includes(normalized) ? normalized : null
    }

    function getStoredLanguage() {
        return normalizeLanguage(localStorage.getItem(STORAGE_KEY))
    }

    function translatePage(root = document) {
        root.querySelectorAll("[data-i18n]").forEach((element) => {
            element.textContent = window.i18next.t(element.dataset.i18n)
        })
        root.querySelectorAll("[data-i18n-html]").forEach((element) => {
            element.innerHTML = window.i18next.t(element.dataset.i18nHtml)
        })
        ;["placeholder", "aria-label", "title", "alt"].forEach((attribute) => {
            const dataAttribute = `data-i18n-${attribute}`
            root.querySelectorAll(`[${dataAttribute}]`).forEach((element) => {
                element.setAttribute(
                    attribute,
                    window.i18next.t(element.getAttribute(dataAttribute)),
                )
            })
        })
    }

    async function changeLanguage(language, options = {}) {
        const normalized = normalizeLanguage(language) || "it"
        if (options.persist !== false)
            localStorage.setItem(STORAGE_KEY, normalized)
        await window.i18next.changeLanguage(normalized)
        return normalized
    }

    const initialLanguage = getStoredLanguage() || "it"
    localStorage.setItem(STORAGE_KEY, initialLanguage)
    document.documentElement.lang = initialLanguage

    const ready = window.i18next.init({
        resources,
        lng: initialLanguage,
        fallbackLng: "it",
        supportedLngs: SUPPORTED_LANGUAGES,
        load: "languageOnly",
        initAsync: false,
        interpolation: { escapeValue: false },
    })

    window.i18next.on("languageChanged", (language) => {
        document.documentElement.lang = normalizeLanguage(language) || "it"
        translatePage()
        window.dispatchEvent(
            new CustomEvent("marketplace:language-changed", {
                detail: { language: document.documentElement.lang },
            }),
        )
    })

    window.marketplaceI18n = {
        STORAGE_KEY,
        SUPPORTED_LANGUAGES,
        ready,
        changeLanguage,
        getLanguage: () =>
            normalizeLanguage(window.i18next.resolvedLanguage) ||
            initialLanguage,
        getStoredLanguage,
        translatePage,
        t: (...args) => window.i18next.t(...args),
    }
    window.marketplaceT = (...args) => window.i18next.t(...args)

    window.addEventListener("storage", (event) => {
        if (event.key !== STORAGE_KEY) return
        const language = normalizeLanguage(event.newValue) || "it"
        changeLanguage(language, { persist: false })
    })

    const applyInitialTranslations = () => {
        Promise.resolve(ready).then(() => translatePage())
    }
    if (document.readyState === "loading") {
        document.addEventListener(
            "DOMContentLoaded",
            applyInitialTranslations,
            { once: true },
        )
    } else {
        applyInitialTranslations()
    }
